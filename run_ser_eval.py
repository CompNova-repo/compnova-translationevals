#!/usr/bin/env python3
"""run_ser_eval.py — CLI driver for the Speech Emotion Recognition pipeline.

Reuses the same ``AutoFeatureExtractor`` + ``Wav2Vec2Model``-plus-rebuilt-head
loader that ``test_audio_emotion.py`` exposes (no Streamlit, no ``DemoApp``
imports, no SeamlessM4T / Whisper / COMET / MetricX / NLLB downloads).

Two modes:

    Single pair
        python run_ser_eval.py --source data/dral/EN_001_#1.wav \
                               --target data/dral/ES_001_#1.wav

    Batch
        python run_ser_eval.py --batch-dir data/dral --pattern "EN_001_#*.wav"

Both modes print to the console (with optional ANSI colour) **and** append
a fresh timestamped section to ``SER_EVAL_LOG.md`` (overridable via
``--md-out``).

In batch mode, clips that share the same base name minus their language
prefix (e.g. ``EN_001_#1.wav`` ↔ ``ES_001_#1.wav``) are paired automatically
and a cosine match is logged next to the per-clip rows.
"""

from __future__ import annotations

import argparse
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

# Reuse the same loader and inference helpers from the smoke test — when
# one breaks (e.g. a transformers upgrade changes the safetensors layout),
# both break, which is what we want.
ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
from test_audio_emotion import (  # noqa: E402
    SER_LABELS,
    compute_affective_match_score,
    do_audio_emotion,
    load_audio_emotion_pipeline,
)


SER_MODEL_NAME = "ehcalabres/wav2vec2-lg-xlsr-en-speech-emotion-recognition"
# DRAL (and the [ToPi](https://www.nigelward.com/topi-full-data.zip)
# fragments used by the demo) ship with two-letter language prefixes
# like ``EN_`` / ``ES_`` before the underscore.
LANG_PREFIX_LEN = 2


# -----------------------------------------------------------------------
# Small console / formatting helpers
# -----------------------------------------------------------------------

def _use_color() -> bool:
    """Respect the NO_COLOR convention and fall back to a tty check."""
    if os.environ.get("NO_COLOR"):
        return False
    if os.environ.get("FORCE_COLOR"):
        return True
    return sys.stdout.isatty()


def _ansi(code: str, text: str, enabled: bool) -> str:
    if not enabled:
        return text
    return f"\033[{code}m{text}\033[0m"


def _pair_key(name: str) -> str | None:
    """Strip the leading 3-letter language prefix to recover the pair key.

    ``EN_001_#1.wav`` → ``001_#1.wav``. Returns None if the prefix doesn't
    look like a 3-letter language code (i.e. not alphabetic).
    """
    if "_" not in name:
        return None
    head, _, _ = name.partition("_")
    if len(head) != LANG_PREFIX_LEN or not head.isalpha():
        return None
    return name[LANG_PREFIX_LEN + 1:]


# -----------------------------------------------------------------------
# Console reporting
# -----------------------------------------------------------------------

def _print_clip(clip: dict, color: bool) -> None:
    path = clip["path"]
    top = clip["top"]
    print(f"\n=== {path.name} ===")
    print(f"  top-1: {_ansi('36', top['label'], color)}  "
          f"({top['score']:.4f})")
    print("  full distribution:")
    for p in clip["preds"]:
        print(f"    - {p['label']:<10} {p['score']:.4f}")


def _print_pair(pair: dict, color: bool) -> None:
    same = pair["src_top"]["label"] == pair["tgt_top"]["label"]
    code = "32" if same else "33"  # green / yellow
    match_str = f"{pair['match']:.4f}"
    print(
        f"\n--- pair {pair['source'].name} <-> {pair['target'].name} ---"
    )
    print(f"  source top-1: {_ansi(code, pair['src_top']['label'], color)} "
          f"({pair['src_top']['score']:.4f})")
    print(f"  target top-1: {_ansi(code, pair['tgt_top']['label'], color)} "
          f"({pair['tgt_top']['score']:.4f})")
    print(f"  cosine match: {_ansi('1;36', match_str, color)}")


# -----------------------------------------------------------------------
# Markdown logging
# -----------------------------------------------------------------------

_MD_HEADER = (
    "# SER evaluation log\n\n"
    "Each run appends a fresh timestamped section to this file (latest\n"
    "runs at the bottom; the on-disk order matches execution order).\n"
    "Generated by `run_ser_eval.py`.\n"
)


def _append_markdown(md_path: Path, mode_label: str, clips: list[dict],
                     pairs: list[dict]) -> None:
    ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    lines: list[str] = [f"\n## Run @ {ts}\n",
                        f"**Mode:** `{mode_label}`  ",
                        f"**Files evaluated:** {len(clips)}  ",
                        f"**Pairs:** {len(pairs)}\n"]

    if clips:
        lines.append("### Per-clip predictions\n")
        lines.append("| File | Top-1 | Confidence | Top-4 distribution |")
        lines.append("| --- | --- | --- | --- |")
        for clip in clips:
            top4 = ", ".join(
                f"{p['label']} ({p['score']:.2f})" for p in clip["preds"][:4]
            )
            lines.append(
                f"| `{clip['path'].name}` | {clip['top']['label']} | "
                f"{clip['top']['score']:.4f} | {top4} |"
            )
        lines.append("")

    if pairs:
        lines.append("### Pairwise cosine match\n")
        lines.append("| Source | Target | Source top-1 | Target top-1 | Match |")
        lines.append("| --- | --- | --- | --- | --- |")
        for p in pairs:
            lines.append(
                f"| `{p['source'].name}` | `{p['target'].name}` | "
                f"{p['src_top']['label']} ({p['src_top']['score']:.4f}) | "
                f"{p['tgt_top']['label']} ({p['tgt_top']['score']:.4f}) | "
                f"**{p['match']:.4f}** |"
            )
        lines.append("")

    md_path.parent.mkdir(parents=True, exist_ok=True)
    needs_header = not md_path.exists() or md_path.stat().st_size == 0
    with md_path.open("a", encoding="utf-8") as fp:
        if needs_header:
            fp.write(_MD_HEADER)
        fp.write("\n".join(lines))


# -----------------------------------------------------------------------
# Prediction pass
# -----------------------------------------------------------------------

def _predict_all(spec, paths: list[Path], quiet: bool,
                 color: bool) -> dict[Path, list[dict]]:
    """Run do_audio_emotion on each path exactly once and cache by path.

    Prints per-clip results to the console unless ``quiet`` is set.
    """
    out: dict[Path, list[dict]] = {}
    for p in paths:
        preds = do_audio_emotion(spec, str(p))
        clip = {"path": p, "preds": preds, "top": preds[0]}
        out[p] = preds
        if not quiet:
            _print_clip(clip, color)
    return out


def _pair_from_predictions(by_path: dict[Path, list[dict]],
                            quiet: bool, color: bool) -> list[dict]:
    """Pair clips by language-prefix key and compute cosine matches."""
    grouped: dict[str, dict[str, Path]] = {}
    for p in by_path.keys():
        k = _pair_key(p.name)
        if k is None:
            continue
        head = p.name[:LANG_PREFIX_LEN]
        grouped.setdefault(k, {})[head] = p

    pairs: list[dict] = []
    for k, sides in grouped.items():
        if len(sides) < 2:
            continue
        # Sort by language code so the order is deterministic.
        ordered = [sides[h] for h in sorted(sides.keys())]
        # Match the first side to every other side.
        anchor = ordered[0]
        anchor_preds = by_path[anchor]
        for other in ordered[1:]:
            other_preds = by_path[other]
            score = compute_affective_match_score(anchor_preds, other_preds)
            pair = {
                "source": anchor,
                "target": other,
                "src_top": anchor_preds[0],
                "tgt_top": other_preds[0],
                "match": score,
            }
            pairs.append(pair)
            if not quiet:
                _print_pair(pair, color)
    return pairs


# -----------------------------------------------------------------------
# CLI
# -----------------------------------------------------------------------

def _build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="run_ser_eval",
        description=(
            "Run the wav2vec2 Speech Emotion Recognition (SER) pipeline "
            "against one or more WAV files from the command line. Results "
            "are printed to the console and appended to a markdown log."
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=(
            "examples:\n"
            "  python run_ser_eval.py --source data/dral/EN_001_#1.wav "
            "--target data/dral/ES_001_#1.wav\n"
            "  python run_ser_eval.py --batch-dir data/dral "
            '--pattern "EN_001_#*.wav" --md-out runs.md\n'
        ),
    )
    mode = p.add_mutually_exclusive_group(required=True)
    mode.add_argument("--source",
                      help="Source wav path (pair mode).")
    mode.add_argument("--batch-dir",
                      help="Directory of wavs (batch mode).")
    p.add_argument("--target",
                   help="Target wav path (pair mode, requires --source).")
    p.add_argument("--pattern", default="*.wav",
                   help="Glob for batch mode (default: *.wav).")
    p.add_argument("--md-out", default="SER_EVAL_LOG.md",
                   help="Path to append markdown results "
                        "(default: SER_EVAL_LOG.md).")
    p.add_argument("--quiet", action="store_true",
                   help="Suppress per-clip console output (still writes markdown).")
    p.add_argument("--no-color", action="store_true",
                   help="Disable ANSI colour in console output.")
    return p


def main(argv: list[str] | None = None) -> int:
    parser = _build_parser()
    args = parser.parse_args(argv)
    color = not args.no_color and _use_color()

    spec = load_audio_emotion_pipeline()
    print(f"loaded SER model: {SER_MODEL_NAME}")
    print(f"id2label = " + ", ".join(f"{i}:{lbl}" for i, lbl in enumerate(SER_LABELS)))

    if args.source is not None:
        if not args.target:
            parser.error("--source requires --target")
        src = Path(args.source)
        tgt = Path(args.target)
        if not src.exists():
            print(f"!! missing source: {src}", file=sys.stderr)
            return 1
        if not tgt.exists():
            print(f"!! missing target: {tgt}", file=sys.stderr)
            return 1
        by_path = _predict_all(spec, [src, tgt], args.quiet, color)
        pairs = _pair_from_predictions(by_path, args.quiet, color)
        clips = [
            {"path": p, "preds": by_path[p], "top": by_path[p][0]}
            for p in (src, tgt)
        ]
        _append_markdown(Path(args.md_out), "pair", clips, pairs)
        print(f"\nresults appended to: {args.md_out}")
        return 0

    # batch mode
    batch_dir = Path(args.batch_dir)
    if not batch_dir.is_dir():
        print(f"!! not a directory: {batch_dir}", file=sys.stderr)
        return 1
    files = sorted(batch_dir.glob(args.pattern))
    if not files:
        print(f"!! no files matched {args.pattern!r} under {batch_dir}",
              file=sys.stderr)
        return 1
    print(f"batch mode: {len(files)} file(s) matched {args.pattern!r} "
          f"under {batch_dir}")
    by_path = _predict_all(spec, files, args.quiet, color)
    pairs = _pair_from_predictions(by_path, args.quiet, color)
    clips = [
        {"path": p, "preds": by_path[p], "top": by_path[p][0]}
        for p in files
    ]
    _append_markdown(Path(args.md_out), "batch", clips, pairs)
    print(f"\nresults appended to: {args.md_out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
